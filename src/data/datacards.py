"""Write one data card per dataset to docs/data_cards/<name>.md (piece 2).

Human facts (source, licence, origin, role, known issues) come from configs/datasets.yaml.
Every number comes from the latest audit run (experiments/audit/) or from the loader metadata in
data/processed/. Nothing is typed by hand (AGENTS.md rule 1).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "configs" / "datasets.yaml"
RUNS = ROOT / "experiments" / "audit"
PROCESSED = ROOT / "data" / "processed"
SPLITS = ROOT / "data" / "splits"
CARDS = ROOT / "docs" / "data_cards"
SPLIT_FILE = {
    "lovdal": "lovdal_folds.json", "kaggle_runners": "lovdal_folds.json",
    "pamap2": "pamap2_folds.json", "wesad": "wesad_folds.json", "sportdb2": "sportdb2_folds.json",
    "soccermon": "soccermon_lopo.json", "pmdata": "pmdata_lopo.json",
    "sirp600": "sirp600_demo_split.json",
}
PROCESSED_META = {
    "lovdal": ["lovdal/day_meta.json", "lovdal/week_meta.json"],
    "pamap2": ["pamap2/windows_meta.json"], "wesad": ["wesad/windows_meta.json"],
    "soccermon": ["soccermon/daily_meta.json"], "pmdata": ["pmdata/daily_meta.json"],
    "sportdb2": ["sportdb2/hr_meta.json"], "sirp600": ["sirp600/meta.json"],
    "ziya07_wearable": ["ziya07_wearable/meta.json"],
}


def latest_audit() -> tuple[str, dict]:
    run = sorted(p for p in RUNS.iterdir() if (p / "audit.json").exists())[-1]
    return run.name, json.loads((run / "audit.json").read_text(encoding="utf-8"))["datasets"]


def _fmt(value) -> str:
    if isinstance(value, dict):
        return ", ".join(f"{k}: {_fmt(v)}" for k, v in value.items())
    if isinstance(value, list):
        return ", ".join(_fmt(v) for v in value)
    return str(value)


def card(name: str, cfg: dict, res: dict, run_id: str) -> str:
    t = res.get("table", {})
    lines = [
        f"# Data card: {cfg['name']}",
        "",
        f"_Generated by `python tasks.py data` from `configs/datasets.yaml`, audit run "
        f"`{run_id}` and `data/processed/` metadata. Do not edit by hand._",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Number | #{cfg['number']} |",
        f"| Source | {cfg.get('source_url', '')} |",
        f"| Licence | {cfg.get('licence', '')} |",
        f"| Accessed | {cfg.get('access_date') or 'not downloaded'} |",
        f"| Origin | {cfg.get('origin')}: {cfg.get('origin_evidence', '')} |",
        f"| Role | {cfg.get('role', 'pending')} |",
        f"| Status | {res.get('status', 'not audited')} |",
        f"| Data fingerprint | `{res.get('fingerprint') or '-'}` |",
        "",
        f"## Counts (audit run `{run_id}`)",
    ]
    labels = {"subjects": "People / subjects", "size": "Size", "channels": "Channels / features",
              "labels": "Labels", "injury": "Injury labels", "time_series": "Time series"}
    for key, label in labels.items():
        lines.append(f"- **{label}:** {t.get(key, '-')}")
    if res.get("size_mb") is not None:
        lines.append(f"- **Files read:** {len(res.get('files', []))} ({res['size_mb']} MB)")
    lines += ["", "## Missing values and duplicates"]
    miss = res.get("missingness")
    lines.append(f"- **Missing:** {_fmt(miss) if miss else 'none reported'}")
    lines.append(f"- **Duplicates:** {_fmt(res.get('duplicates'))}")
    plaus = res.get("plausibility")
    if plaus:
        lines += ["", "## Plausibility checks", f"- {_fmt(plaus)}"]
    metas = [PROCESSED / m for m in PROCESSED_META.get(name, []) if (PROCESSED / m).exists()]
    if metas:
        lines += ["", "## Processed data (piece 2)"]
        for m in metas:
            meta = json.loads(m.read_text(encoding="utf-8"))
            keep = {k: v for k, v in meta.items()
                    if k not in ("feature_names", "columns", "athlete_ids", "workers")}
            lines.append(f"- `data/processed/{m.relative_to(PROCESSED).as_posix()}`: {_fmt(keep)}")
    split = SPLIT_FILE.get(name)
    if split and (SPLITS / split).exists():
        s = json.loads((SPLITS / split).read_text(encoding="utf-8"))
        lines += ["", "## Splits",
                  f"- `data/splits/{split}` ({s['meta']['decision']}): {s['meta']['method']}"]
        if name == "kaggle_runners":
            lines.append("- Same data as Lövdal: use the Lövdal split.")
    notes = list(res.get("notes", [])) + list(cfg.get("known_issues", []))
    if notes:
        lines += ["", "## Known issues"] + [f"- {n}" for n in notes]
    return "\n".join(lines) + "\n"


def write_cards() -> list[Path]:
    cfgs = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))["datasets"]
    run_id, results = latest_audit()
    CARDS.mkdir(parents=True, exist_ok=True)
    written = []
    for name, cfg in sorted(cfgs.items(), key=lambda kv: kv[1]["number"]):
        path = CARDS / f"{name}.md"
        path.write_text(card(name, cfg, results.get(name, {}), run_id), encoding="utf-8")
        written.append(path)
    return written


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    for p in write_cards():
        print("wrote", p.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
